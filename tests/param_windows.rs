#[test]
fn param_windows_match_scipy() {
    let mut engine = Engine::default();
    for (expr, expected) in CASES {
        engine.execute(&format!("w = {expr};")).unwrap();
        let w = &engine.variables["w"];
        assert_eq!((w.rows(), w.cols()), (expected.len(), 1), "{expr}");
        for (i, (a, b)) in w.data().iter().zip(expected.iter()).enumerate() {
            assert!(
                (a - b).abs() <= 1e-12 * (1. + b.abs()),
                "{expr} [{i}]: {a} != {b}"
            );
        }
    }
}

#[test]
fn param_windows_edges_and_errors() {
    let mut engine = Engine::default();
    engine
        .execute("a = gausswin(1); b = tukeywin(0); c = chebwin(1); d = tukeywin(5, 0); e = tukeywin(5, []); f = taylorwin(6, [], -40); g = parzenwin(2.4);")
        .unwrap();
    assert_eq!(engine.variables["a"].data(), &[1.]);
    assert_eq!(
        (engine.variables["b"].rows(), engine.variables["b"].cols()),
        (0, 1)
    );
    assert_eq!(engine.variables["c"].data(), &[1.]);
    assert_eq!(engine.variables["d"].data(), &[1.; 5]);
    engine.execute("e2 = tukeywin(5);").unwrap();
    assert_eq!(engine.variables["e"].data(), engine.variables["e2"].data());
    assert_eq!(engine.variables["f"].rows(), 6);
    assert_eq!(engine.variables["g"].rows(), 2);
    for bad in [
        "chebwin(8, -3)",
        "taylorwin(8, 4, 30)",
        "taylorwin(8, 2.5)",
        "gausswin(-1)",
        "bohmanwin(4, 2)",
    ] {
        assert!(
            engine.execute(&format!("x = {bad};")).is_err(),
            "{bad} should fail"
        );
    }
}

#[test]
fn taylorwin_bounds_its_coefficient_work() {
    // SciPy windows.taylor(1000, 100, 30, norm=False) at samples 1, 2, 251, 500, 1000 and its sum.
    let mut engine = Engine::default();
    engine
        .execute("w = taylorwin(1000, 100); s = sum(w);")
        .unwrap();
    let w = engine.variables["w"].data();
    for (i, b) in [
        (0, 3.7560952526502867),
        (1, 3.5317282298758927),
        (250, 1.0229535197806543),
        (499, 1.4694943971433578),
        (999, 3.7560952526502867),
    ] {
        assert!(
            (w[i] - b).abs() <= 1e-10 * b,
            "taylorwin(1000,100)[{i}]: {} != {b}",
            w[i]
        );
    }
    assert!((engine.variables["s"].data()[0] - 999.9999999999998).abs() < 1e-8);
    // NBAR = 1e6 would need ~1e12 coefficient iterations: rejected at once.
    let start = std::time::Instant::now();
    let err = engine.execute("x = taylorwin(2, 1000000);").unwrap_err();
    assert!(err.contains("taylorwin: NBAR too large"), "{err}");
    assert!(start.elapsed().as_secs_f64() < 1., "{:?}", start.elapsed());
}
