#[test]
fn invalid_parameters_search_and_workspace_rejected() {
    let (n, x, t) = api_problem();
    for (name, key, value) in [
        ("traingdm", "mc", 1.1),
        ("traingdx", "lr_dec", 1.),
        ("trainrp", "delta0", 0.),
        ("trainbr", "mu_inc", 1.),
        ("trainbfg", "up_lim", 1.),
        ("trainbfg", "batch_frag", 1.),
    ] {
        let mut opts = TrainOptions {
            train_fcn: name.into(),
            ..Default::default()
        };
        opts.parameters.insert(key.into(), value);
        assert!(train::train(&n, &x, &t, opts, &mut |_| ControlFlow::Continue(())).is_err());
    }
    for name in TRAINERS {
        let opts = TrainOptions {
            train_fcn: name.into(),
            memory_bytes: 128,
            ..Default::default()
        };
        assert!(
            train::train(&n, &x, &t, opts, &mut |_| ControlFlow::Continue(()))
                .unwrap_err()
                .contains("memory")
        );
    }
    let opts = TrainOptions {
        train_fcn: "trainbfg".into(),
        string_parameters: [("searchFcn".into(), "srchcha".into())].into(),
        ..Default::default()
    };
    assert!(
        train::train(&n, &x, &t, opts, &mut |_| ControlFlow::Continue(()))
            .unwrap_err()
            .contains("srchbac")
    );
    let opts = TrainOptions {
        train_fcn: "trainbr".into(),
        perform_fcn: "mae".into(),
        ..Default::default()
    };
    assert!(
        train::train(&n, &x, &t, opts, &mut |_| ControlFlow::Continue(()))
            .unwrap_err()
            .contains("mse or sse")
    );
}
#[test]
fn release_benchmark_one_and_four_workers() {
    let (n, x, t) = api_problem();
    for name in TRAINERS {
        let mut expected: Option<Vec<f64>> = None;
        for workers in [1, 4] {
            let pool = rayon::ThreadPoolBuilder::new()
                .num_threads(workers)
                .build()
                .unwrap();
            pool.install(|| {
                let start=Instant::now();
                let mut opts=TrainOptions {train_fcn:name.into(),..Default::default()};
                opts.parameters.insert("epochs".into(),5.); opts.parameters.insert("min_grad".into(),0.);
                let (result,tr)=train::train(&n,&x,&t,opts,&mut |_|ControlFlow::Continue(())).unwrap();
                if let Some(ref expected)=expected {near(&result.getwb(),expected);} else {expected=Some(result.getwb());}
                eprintln!("nnet_trainers release benchmark: {name}, workers={workers}, 1-3-1, samples=5, weights=10, epochs={}, memory_cap=256MiB, elapsed={:?}",tr.num_epochs,start.elapsed());
            });
        }
    }
}
