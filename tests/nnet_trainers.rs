#[test]
fn documented_defaults_and_reset_table() {
    let common = [
        ("epochs", 1000.),
        ("goal", 0.),
        ("show", 25.),
        ("showCommandLine", 0.),
        ("showWindow", 1.),
        ("time", f64::INFINITY),
    ];
    let extras: [&[(&str, f64)]; 6] = [
        &[
            ("mu", 0.005),
            ("mu_dec", 0.1),
            ("mu_inc", 10.),
            ("mu_max", 1e10),
        ],
        &[("lr", 0.01)],
        &[("lr", 0.01), ("mc", 0.9)],
        &[
            ("lr", 0.01),
            ("mc", 0.9),
            ("lr_inc", 1.05),
            ("lr_dec", 0.7),
            ("max_perf_inc", 1.04),
        ],
        &[
            ("lr", 0.01),
            ("delt_inc", 1.2),
            ("delt_dec", 0.5),
            ("delta0", 0.07),
            ("deltamax", 50.),
        ],
        &[
            ("scal_tol", 20.),
            ("alpha", 0.001),
            ("beta", 0.1),
            ("delta", 0.01),
            ("gamma", 0.1),
            ("low_lim", 0.1),
            ("up_lim", 0.5),
            ("maxstep", 100.),
            ("minstep", 1e-6),
            ("bmax", 26.),
            ("batch_frag", 0.),
        ],
    ];
    let mut e = Engine::default();
    run(&mut e, "n=fitnet(3);");
    for (name, extra) in TRAINERS.iter().zip(extras) {
        run(
            &mut e,
            &format!("n.trainParam.epochs=7; n.trainFcn='{name}';"),
        );
        let mut expected: train::Parameters = common
            .into_iter()
            .chain(extra.iter().copied())
            .map(|(k, v)| (k.into(), v))
            .collect();
        expected.insert(
            "min_grad".into(),
            if *name == "trainbr" {
                1e-7
            } else if *name == "trainbfg" {
                1e-6
            } else {
                1e-5
            },
        );
        expected.insert("max_fail".into(), if *name == "trainbr" { 0. } else { 6. });
        assert_eq!(train::defaults(name).unwrap(), expected);
        for (k, v) in expected {
            let literal = if v.is_infinite() {
                "Inf".to_owned()
            } else {
                v.to_string()
            };
            run(&mut e, &format!("assert(n.trainParam.{k}=={literal});"));
        }
        if *name == "trainbfg" {
            run(&mut e, "assert(strcmp(n.trainParam.searchFcn,'srchbac'));");
        }
    }
}
fn api_problem() -> (Network, Matrix, Matrix) {
    let x = Matrix::from_column_vec(1, 5, vec![-1., -0.5, 0., 0.5, 1.]).unwrap();
    let t = x.map(|v| v * v + 0.2 * v);
    let mut n = Network::new(&[3], false, false).unwrap();
    n.input.process_fcns.clear();
    n.output.process_fcns.clear();
    n.configure(&x, &t, &AtomicBool::new(false)).unwrap();
    n.setwb(
        &(1..=n.num_weight_elements())
            .map(|i| i as f64 * 0.025 - 0.25)
            .collect::<Vec<_>>(),
    )
    .unwrap();
    (n, x, t)
}
#[test]
fn all_shared_stops_and_bayesian_mu_stop() {
    let (n, x, t) = api_problem();
    for (name, key, value, stop) in [
        ("traingd", "epochs", 0., "Maximum epoch reached."),
        ("traingdm", "goal", 1., "Performance goal met."),
        ("traingdx", "min_grad", 100., "Minimum gradient reached."),
        ("trainrp", "time", 0., "Maximum time elapsed."),
        ("trainbr", "mu_max", 0.001, "Maximum MU reached."),
    ] {
        let mut opts = TrainOptions {
            train_fcn: name.into(),
            ..Default::default()
        };
        opts.parameters.insert(key.into(), value);
        let (_, tr) = train::train(&n, &x, &t, opts, &mut |_| ControlFlow::Continue(())).unwrap();
        assert_eq!(tr.stop, stop);
    }
    // A fixed training point and incompatible validation target reliably fail.
    let x = Matrix::from_column_vec(1, 2, vec![0., 0.]).unwrap();
    let t = Matrix::from_column_vec(1, 2, vec![1., -1.]).unwrap();
    let mut opts = TrainOptions {
        train_fcn: "trainbfg".into(),
        division: Division::Indices([vec![0], vec![1], vec![]]),
        ..Default::default()
    };
    opts.parameters
        .extend([("max_fail".into(), 1.), ("min_grad".into(), 0.)]);
    let (result, tr) = train::train(&n, &x, &t, opts, &mut |_| ControlFlow::Continue(())).unwrap();
    assert_eq!(tr.stop, "Validation stop.");
    assert_eq!(tr.best_epoch, 0);
    assert_eq!(result.getwb(), n.getwb());
}
#[test]
fn progress_and_cancel_all_six_are_atomic() {
    let (n, x, t) = api_problem();
    let original = n.getwb();
    for name in TRAINERS {
        let opts = TrainOptions {
            train_fcn: name.into(),
            ..Default::default()
        };
        let (result, tr) = train::train(&n, &x, &t, opts, &mut |r| {
            if r.epoch == 1 {
                ControlFlow::Break(())
            } else {
                ControlFlow::Continue(())
            }
        })
        .unwrap();
        assert_eq!(tr.stop, "User stop.");
        assert_eq!(tr.num_epochs, 1);
        assert_ne!(result.getwb(), original);
        let cancel = Arc::new(AtomicBool::new(false));
        let opts = TrainOptions {
            train_fcn: name.into(),
            cancel: cancel.clone(),
            ..Default::default()
        };
        let result = train::train(&n, &x, &t, opts, &mut |r| {
            if r.epoch == 1 {
                cancel.store(true, Ordering::Relaxed);
            }
            ControlFlow::Continue(())
        });
        assert!(result.is_err());
        assert_eq!(n.getwb(), original);
    }
}
