#[test]
fn step_review_edge_cases_error_or_answer_without_panicking() {
    let mut e = Engine::default();
    // DiffMinChange above DiffMaxChange is an argument error, not a clamp panic.
    let msg = error(
        &mut e,
        "f = fit([1;2;3],[1;2;3],'a*x','StartPoint',1,'DiffMinChange',1,'DiffMaxChange',0.1);",
    );
    assert!(msg.contains("DiffMinChange"), "{msg}");
    // -0 and +0 are the same point for integrate.
    run(
        &mut e,
        "f = cfit(fittype('poly1'),1,0); v = integrate(f,-0,0); w = integrate(f,[-0;0;1],0);",
    );
    assert_eq!(numbers(&e, "v"), vec![0.]);
    close("integrate", &numbers(&e, "w"), &[0., 0., 0.5], 1e-12);
    // A coefficient fixed by Lower == Upper has NaN confidence bounds; the free one keeps finite bounds.
    run(
        &mut e,
        "g = fit([1;2;3;4],[3.1;4.9;7.2;8.8],'a*x+b','StartPoint',[1 1],'Lower',[-Inf 1],'Upper',[Inf 1]); ci = confint(g);",
    );
    let ci = numbers(&e, "ci");
    assert!(ci[0].is_finite() && ci[1].is_finite(), "{ci:?}");
    assert!(ci[2].is_nan() && ci[3].is_nan(), "{ci:?}");
}
