#[test]
fn fitoptions_forms_and_struct_fields() {
    let mut e = Engine::default();
    run(
        &mut e,
        "o = fitoptions('gauss2'); lo = o.Lower; m = o.Method; \
         p = fitoptions('poly2'); pf = fieldnames(p); \
         q = fitoptions('Method', 'NonlinearLeastSquares', 'StartPoint', [1 2], 'MaxIter', 50); \
         q2 = fitoptions(q, 'TolFun', 1e-8); it = q2.MaxIter; tf = q2.TolFun; sp = q2.StartPoint; \
         n = fitoptions(); nf = fieldnames(n);",
    );
    let inf = f64::NEG_INFINITY;
    assert_eq!(numbers(&e, "lo"), [inf, inf, 0., inf, inf, 0.]);
    assert_eq!(text(&e, "m"), "NonlinearLeastSquares");
    assert_eq!(numbers(&e, "it"), [50.]);
    assert_eq!(numbers(&e, "tf"), [1e-8]);
    assert_eq!(numbers(&e, "sp"), [1., 2.]);
    run(
        &mut e,
        "ok = isequal(pf, {'Normalize';'Exclude';'Weights';'Method';'Robust';'Lower';'Upper'}) \
         && isequal(nf, {'Normalize';'Exclude';'Weights';'Method'});",
    );
    assert_eq!(numbers(&e, "ok"), [1.]);
    // Options value semantics: a copy keeps its own fields.
    run(
        &mut e,
        "a = fitoptions('exp1'); b = a; b.Lower = [0 0]; la = a.Lower; lb = b.Lower;",
    );
    assert!(numbers(&e, "la").is_empty());
    assert_eq!(numbers(&e, "lb"), [0., 0.]);
    // Levenberg-Marquardt reaches the same optimum.
    let mut e = engine_with(X_EXP1, Y_EXP1);
    run(
        &mut e,
        "f = fit(x, y, 'exp1', 'Algorithm', 'Levenberg-Marquardt'); c = coeffvalues(f);",
    );
    close("levenberg-marquardt", &numbers(&e, "c"), B_EXP1, 1e-6);
}

