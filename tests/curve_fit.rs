#[test]
fn error_cases_are_reported() {
    let mut e = Engine::default();
    run(&mut e, "x = (1:6)'; y = [2 4 5 8 9 13]';");
    for (code, expected) in [
        (
            "fit(x, y(1:5), 'poly1')",
            "X and Y must have the same number of rows",
        ),
        ("fit(x(1:2), y(1:2), 'poly2')", "insufficient data"),
        ("fit(x, y, 'gauss9')", "Unknown library model 'gauss9'"),
        ("fit(x, y, 'rat60')", "Unknown library model"),
        (
            "fit(x, y, 'exp1', 'Lower', [0 0 0])",
            "Lower must have one value per coefficient (2)",
        ),
        (
            "fit(x, y, 'exp1', 'StartPoint', [1 1 1])",
            "StartPoint must have one value per coefficient",
        ),
        (
            "fit(x, y, 'exp1', 'Lower', [1 1], 'Upper', [0 0])",
            "Lower bounds must be less than or equal to Upper bounds",
        ),
        (
            "fit(x, y, 'exp1', 'Bogus', 1)",
            "Invalid fit option 'Bogus'",
        ),
        (
            "fit(x, y, 'poly1', 'StartPoint', [1 1])",
            "not an option of the LinearLeastSquares",
        ),
        (
            "fit(x, y, 'exp1', 'Weights', [1 2])",
            "Weights must have one value per data point",
        ),
        (
            "fit(x, y, 'poly1', 'Exclude', 9)",
            "Exclude indices must be integers",
        ),
        ("fit([x x], y, 'poly1')", "X must have one column"),
        ("fit(x, y, 'poly11')", "two columns"),
        ("fittype('a*t')", "independent variable 'x' does not appear"),
        ("fittype('a*x + foo(b)')", "'foo'"),
        (
            "confint(5)",
            "Undefined function 'confint' for input arguments of type 'double'",
        ),
        ("fit(x, [y(1:5); NaN], 'poly1')", "NaN or Inf"),
        ("f = fit(x, y, 'poly1'); f.p1 = 3;", "read-only"),
        (
            "f = fit(x, y, 'poly1'); f.nothing",
            "No coefficient, problem parameter or method 'nothing'",
        ),
        ("fit(x, y, 'lowess')", "not supported yet"),
        ("fit(x, y)", "fit(x, y, fitType)"),
    ] {
        let message = error(&mut e, code);
        assert!(message.contains(expected), "{code}: {message}");
    }
    // As many coefficients as points: a warning and NaN bounds.
    let out = run(&mut e, "f = fit(x(1:3), y(1:3), 'poly2'); c = confint(f);");
    assert!(
        out.contains("Warning:") && out.contains("degrees of freedom"),
        "{out}"
    );
    assert!(numbers(&e, "c").iter().all(|v| v.is_nan()));
}

