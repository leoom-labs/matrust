use super::*;

fn synthetic(
    parent: Option<mat::Encoded<'static>>,
    children: Vec<mat::Encoded<'static>>,
) -> Vec<u8> {
    let mut props = vec![
        ("XData", num(&[1., 3.])),
        ("YData", num(&[2., 4.])),
        ("FaceColor", num(&[0., 0., 1.])),
        ("LineStyle", mat::text("--")),
        ("LineWidth", num(&[2.])),
    ];
    if let Some(edge) = parent {
        props.push(("EdgeColor", edge));
    }
    let bar = node(
        "specgraph.barseries",
        3.,
        props,
        children
            .into_iter()
            .enumerate()
            .map(|(i, edge)| {
                node(
                    "patch",
                    10. + i as f64,
                    vec![("EdgeColor", edge)],
                    vec![],
                    &[],
                )
            })
            .collect(),
        &[],
    );
    mat::file(mat::structure(
        "hgS_070000",
        node(
            "figure",
            1.,
            vec![],
            vec![node("axes", 2., vec![], vec![bar], &[0.; 4])],
            &[],
        ),
    ))
    .unwrap()
}
#[test]
fn authentic_reference_bar_children_preserve_independent_black_edges() {
    // Authentic saved bytes, not generated by this test or MatRust. The parent
    // omits EdgeColor; its serialized Patch child explicitly stores black RGB.
    let bytes = include_bytes!("../../tests/fixtures/fig/matlab-bars.fig");
    let f = decode_matlab_figure(bytes).unwrap();
    assert_eq!(f.series.len(), 2);
    for s in &f.series {
        assert_eq!(s.kind, PlotKind::Bar);
        assert_eq!(s.face_edge_color, Some([0; 3]));
        assert_eq!(s.pattern, LinePattern::Solid);
        assert_eq!(s.line_width, Some(0.5));
        assert_ne!(s.color, [0; 3]);
        assert_eq!(s.points.len(), 3);
    }
    assert!((f.series[0].bar_width - 0.8 * 2. / 7.).abs() < 1e-14);
    assert_eq!(f.series[0].bar_offset, -1. / 7.);
    assert_eq!(f.series[1].bar_offset, 1. / 7.);
    assert!(
        encode_matlab_figure(&f).is_err(),
        "Saved child appearance does not prove Bar reconstruction"
    );
}
#[test]
fn supported_parent_edge_takes_precedence_and_uniform_children_are_bounded_fallback() {
    for (parent, children, expected) in [
        (
            Some(num(&[1., 0., 0.])),
            vec![num(&[0., 0., 0.])],
            Some([255, 0, 0]),
        ),
        (Some(mat::text("none")), vec![num(&[0., 0., 0.])], None),
        (
            None,
            vec![num(&[0., 1., 0.]), num(&[0., 1., 0.])],
            Some([0, 255, 0]),
        ),
        (
            Some(mat::text("flat")),
            vec![num(&[0., 1., 0.])],
            Some([0, 255, 0]),
        ),
        (None, vec![mat::text("none")], None),
        (None, vec![num(&[1., 0., 0.]), num(&[0., 1., 0.])], None),
        (Some(mat::text("auto")), vec![mat::text("flat")], None),
        (None, vec![], None),
    ] {
        let f = decode_matlab_figure(&synthetic(parent, children)).unwrap();
        assert_eq!(f.series[0].face_edge_color, expected);
        assert_eq!(f.series[0].color, [0, 0, 255]);
        assert_eq!(f.series[0].pattern, LinePattern::Dashed);
        assert_eq!(f.series[0].line_width, Some(2.));
        assert!(f.series[0].points.iter().eq([[1., 2.], [3., 4.]]));
    }
    let children = (0..65).map(|_| num(&[0., 0., 0.])).collect();
    let f = decode_matlab_figure(&synthetic(None, children)).unwrap();
    assert!(f.series[0].face_edge_color.is_none());
}
